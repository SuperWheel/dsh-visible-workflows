// Compile this independent native component; never install, launch, authenticate
// or access Keychain. Ad-hoc integrity signing is not a global isolation claim.
import { spawnSync } from 'node:child_process'
import { mkdirSync, copyFileSync, readdirSync, readFileSync, lstatSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { join, resolve } from 'node:path'

if (process.platform !== 'darwin' || !['arm64','x64'].includes(process.arch)) throw Error('OS Secret broker build requires supported macOS')
const root = fileURLToPath(new URL('.', import.meta.url))
const app = join(root, 'dist/Workflow OS Secret Broker.app')
const macos = join(app, 'Contents/MacOS')
mkdirSync(macos, { recursive: true })
mkdirSync(join(root, '.build-cache'), { recursive: true })
copyFileSync(join(root, 'Info.plist'), join(app, 'Contents/Info.plist'))
const sources = readdirSync(join(root, 'Sources')).filter(name => name.endsWith('.swift')).map(name => join(root, 'Sources', name)).sort()
const run = (binary, args) => {
  const result = spawnSync(binary, args, { stdio: 'inherit', shell: false, env: { PATH: '/usr/bin:/bin', LANG: 'en_US.UTF-8' } })
  if (result.error || result.status !== 0) process.exit(1)
}
run('/usr/bin/xcrun', ['swiftc', '-O', '-whole-module-optimization', '-module-cache-path', join(root, '.build-cache'), '-target', `${process.arch === 'arm64' ? 'arm64' : 'x86_64'}-apple-macosx15.0`, '-framework', 'AppKit', '-framework', 'Security', '-framework', 'LocalAuthentication', ...sources, '-o', join(macos, 'WorkflowOSSecretBroker')])
run('/usr/bin/codesign', ['--force', '--sign', '-', '--options', 'runtime', '--timestamp=none', '--identifier', 'com.deepseekharness.workflow.os-secret-broker', app])
run('/usr/bin/codesign', ['--verify', '--strict', '--deep', app])
const files = []
const walk = relative => {
  for (const name of readdirSync(join(app, relative)).sort()) {
    const entry = relative ? `${relative}/${name}` : name
    const file = join(app, entry), stat = lstatSync(file)
    if (stat.isSymbolicLink() || (!stat.isDirectory() && (!stat.isFile() || stat.nlink !== 1))) throw Error('Unsafe OS broker bundle member')
    if (stat.isDirectory()) walk(entry)
    else files.push({ path: entry, size: stat.size, sha256: createHash('sha256').update(readFileSync(file)).digest('hex') })
  }
}
walk('')
const manifest = JSON.stringify({ version: 1, identifier: 'com.deepseekharness.workflow.os-secret-broker', files }, null, 2) + '\n'
const digest = createHash('sha256').update(manifest).digest('hex')
writeFileSync(join(root, 'dist/integrity.json'), manifest)
writeFileSync(resolve(root, '../../src/host/os-secret-manifest.ts'), `// Generated by native/os-secret-broker/build.mjs. Rebuild Host after native changes.\n// This fixed digest establishes artifact integrity, not global isolation.\nexport const OS_SECRET_BROKER_MANIFEST_SHA256: string | null = ${JSON.stringify(digest)}\n`)
process.stdout.write('Built OS Secret broker; no authentication, Keychain access, installation or global policy changes.\n')
